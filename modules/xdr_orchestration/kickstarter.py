# modules/xdr_orchestration/kickstarter.py
#
# The Kickstarter: the running LogSim console GENERATES a self-contained PowerShell
# one-shot that turns a bare Windows box into a preflight-green attack target — so
# there is no hand-editing on the box. The console bakes in what it already knows:
#   • its own IP/URL (to scope the WinRM firewall rule + set the phone-home URL),
#   • a scoped token (so the box can POST readiness back to /api/v1/attack/register),
#   • exactly the atomics the selected story needs (technique IDs → -GetPrereqs).
#
# What the generated script does (run once, elevated, on the box):
#   1. Enable/configure WinRM, firewall rule SCOPED to the console IP, and
#      LocalAccountTokenFilterPolicy=1 (local admin gets a full token remotely).
#   2. Install Invoke-AtomicRedTeam + atomics UNATTENDED (NuGet provider, trusted
#      PSGallery, powershell-yaml) -- no approval prompts, so it also works over WinRM.
#   3. Stage builtin-payload tooling (e.g. ProcDump) for the non-Atomic stages.
#   4. Verify the Cortex XDR agent (cyserver) is installed and Running.
#   5. Phone home readiness + a provisioning inventory so the console's health tile
#      reflects exactly what the box has.
#   6. Register a SELF-HEAL scheduled task (boot + daily) that re-runs the script in
#      -Refresh mode -- the "run once" engine (below).
#
# RUN ONCE: the self-heal task makes the single run stick. On every refresh it
# re-asserts the config (so a reboot / GPO sweep can't leave the box red), fetches the
# live provisioning MANIFEST from the console (GET /api/v1/attack/kickstarter/manifest
# -- every technique + tool any registered story needs), and installs/stages whatever
# is MISSING. Add a story later and the box picks it up on its next refresh; the
# installer never has to be regenerated or re-run. Each refresh also phones home the
# inventory, so the console always shows what is actually provisioned.
# Idempotent, ships with -Uninstall (removes the task + staged tools), watermarked.
# Lab-only, security-sensitive.

