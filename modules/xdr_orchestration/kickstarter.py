# Token substitution (NOT str.format -- PowerShell is full of { } and $).
_TEMPLATE = r'''#requires -Version 5.1
<#
  LogSim XDR Kickstarter  --  GENERATED by the LogSim console, do not hand-edit.
  Generated at : __GENERATED_AT__
  Console      : __CONSOLE_URL__   (WinRM access scoped to __CONSOLE_IP__)
  Target scope : this box only. LAB-ONLY, security-sensitive (installs offensive tooling).
  Run ELEVATED:  powershell -ExecutionPolicy Bypass -File .\logsim-kickstarter.ps1
  Refresh now :  ... -File .\logsim-kickstarter.ps1 -Refresh   (also runs on a schedule)
  Rollback    :  ... -File .\logsim-kickstarter.ps1 -Uninstall
#>
param(
    [switch]$Uninstall,
    [switch]$NoPhoneHome,
    [switch]$Refresh
)
$ErrorActionPreference = 'Stop'
$ConsoleIP   = '__CONSOLE_IP__'
$ConsoleUrl  = '__CONSOLE_URL__'
$Token       = '__TOKEN__'
$AtomicTests = @(__ATOMIC_TESTS__)      # baked-in fallback if the console manifest is unreachable
$Builtins    = @(__BUILTINS__)          #   "
$ExtraTools  = @(__EXTRA_TOOLS__)       #   " (tools staged for manual / future use)
$AtomicPsd1  = 'C:\AtomicRedTeam\invoke-atomicredteam\Invoke-AtomicRedTeam.psd1'
$ToolsDir    = 'C:\ProgramData\LogSim'
$SelfCopy    = 'C:\ProgramData\LogSim\logsim-kickstarter.ps1'
$TaskName    = 'LogSim XDR Self-Heal'
$RegKeyPath  = 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Policies\System'
$FwRuleName  = 'LogSim WinRM (scoped)'

function Say($m,$c='Gray'){ Write-Host $m -ForegroundColor $c }

if (-not ([Security.Principal.WindowsPrincipal] [Security.Principal.WindowsIdentity]::GetCurrent()
        ).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    Say 'Must run elevated (Run as Administrator).' 'Red'; exit 1
}

# ── Shared helpers (used by both first-run and -Refresh) ──────────────────────

function Assert-Config {
    # WinRM + a firewall rule scoped to the console IP + the local-admin token policy.
    # Idempotent: this is what the self-heal task re-asserts after a reboot / GPO sweep.
    Enable-PSRemoting -Force -SkipNetworkProfileCheck | Out-Null
    try {
        Set-NetFirewallRule -Name 'WINRM-HTTP-In-TCP' -RemoteAddress $ConsoleIP -ErrorAction Stop
    } catch {
        if (-not (Get-NetFirewallRule -DisplayName $FwRuleName -ErrorAction SilentlyContinue)) {
            New-NetFirewallRule -DisplayName $FwRuleName -Direction Inbound -Protocol TCP `
                -LocalPort 5985 -RemoteAddress $ConsoleIP -Action Allow | Out-Null
        }
    }
    New-ItemProperty -Path $RegKeyPath -Name 'LocalAccountTokenFilterPolicy' -PropertyType DWord -Value 1 -Force | Out-Null
}

function Ensure-Atomic {
    param([switch]$FullInstall)
    if ((Test-Path $AtomicPsd1) -and -not $FullInstall) {
        Import-Module $AtomicPsd1 -Force -ErrorAction SilentlyContinue; return
    }
    [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
    $np = Get-PackageProvider -Name NuGet -ErrorAction SilentlyContinue
    if (-not $np -or $np.Version -lt [version]'2.8.5.201') {
        Install-PackageProvider -Name NuGet -MinimumVersion 2.8.5.201 -Force -ForceBootstrap -Scope AllUsers | Out-Null
    }
    if (-not (Get-PSRepository -Name PSGallery -ErrorAction SilentlyContinue)) { Register-PSRepository -Default -ErrorAction SilentlyContinue }
    Set-PSRepository -Name PSGallery -InstallationPolicy Trusted
    if (-not (Get-Module -ListAvailable -Name 'powershell-yaml')) {
        Install-Module -Name 'powershell-yaml' -Force -Scope AllUsers -AllowClobber | Out-Null
    }
    IEX (New-Object Net.WebClient).DownloadString('https://raw.githubusercontent.com/redcanaryco/invoke-atomicredteam/master/install-atomicredteam.ps1')
    Install-AtomicRedTeam -getAtomics -Force
    if (Test-Path $AtomicPsd1) { Import-Module $AtomicPsd1 -Force -ErrorAction SilentlyContinue }
}

function Get-Manifest {
    # The live provisioning list from the console (authoritative + current). Falls back
    # to the baked-in arrays so an offline box still provisions what it shipped with.
    # `tests` is a list of @{ id=<technique>; tests=<test numbers> }.
    $res = @{ tests = $AtomicTests; builtins = $Builtins; extra = $ExtraTools; source = 'baked-in' }
    if ($ConsoleUrl) {
        try {
            $h = @{}; if ($Token) { $h['X-API-Key'] = $Token }
            $m = Invoke-RestMethod -Method Get -TimeoutSec 15 `
                 -Uri ("{0}/api/v1/attack/kickstarter/manifest" -f $ConsoleUrl.TrimEnd('/')) -Headers $h
            if ($m.atomic_tests)     { $res.tests    = @($m.atomic_tests | ForEach-Object { @{ id = $_.id; tests = $_.test_numbers } }) }
            if ($m.builtin_payloads) { $res.builtins = @($m.builtin_payloads) }
            if ($m.extra_tools)      { $res.extra    = @($m.extra_tools | ForEach-Object { @{ name = $_.name; file = $_.file; url = $_.url; member = $_.member } }) }
            $res.source = 'console'
        } catch { Say ("   manifest fetch failed, using baked-in list: {0}" -f $_.Exception.Message) 'DarkGray' }
    }
    return $res
}

function Install-Prereqs($tests) {
    # Resolve prereqs for EXACTLY the pinned test numbers (-TestNumbers), never the whole
    # technique -- otherwise Atomic tries to satisfy every test under the id, including
    # cloud tests whose prereqs pull the retired AzureAD module and fail. -GetPrereqs is
    # idempotent, so this provisions a fresh box and fills gaps for tests added later.
    if (-not (Test-Path $AtomicPsd1)) { return }
    Import-Module $AtomicPsd1 -Force -ErrorAction SilentlyContinue
    foreach ($t in $tests) {
        if (-not $t.id) { continue }
        try {
            if ($t.tests) { Invoke-AtomicTest $t.id -TestNumbers $t.tests -GetPrereqs -ErrorAction SilentlyContinue | Out-Null }
            else          { Invoke-AtomicTest $t.id -GetPrereqs -ErrorAction SilentlyContinue | Out-Null }
        } catch {}
    }
}

function Stage-Tools($builtins) {
    # Stage only what is missing. Add a tool-based stage later and its tool is staged
    # on the next refresh once it appears in the manifest.
    if ($builtins -contains 'procdump_lsass') {
        try {
            New-Item -ItemType Directory -Force -Path $ToolsDir | Out-Null
            $pd = Join-Path $ToolsDir 'procdump64.exe'
            if (-not (Test-Path $pd)) {
                Invoke-WebRequest -Uri 'https://live.sysinternals.com/procdump64.exe' -OutFile $pd -UseBasicParsing -TimeoutSec 60
            }
            if (Test-Path $pd) { Say ("   ProcDump staged at {0}" -f $pd) 'Green' }
            else { Say '   ProcDump not staged (the stage will download at run time).' 'DarkGray' }
        } catch { Say ("   ProcDump staging failed (non-fatal): {0}" -f $_.Exception.Message) 'DarkGray' }
    }
}

function Stage-ExtraTools($tools) {
    # Stage lab tools that no stage auto-fires but an operator or a future stage may
    # need (e.g. Process Hacker). Idempotent (skip if present), non-fatal. A .zip is
    # downloaded and the named member extracted; everything else is a direct download.
    foreach ($t in $tools) {
        if (-not $t.file) { continue }
        try {
            New-Item -ItemType Directory -Force -Path $ToolsDir | Out-Null
            $dest = Join-Path $ToolsDir $t.file
            if (Test-Path $dest) { Say ("   {0} already staged." -f $t.name) 'DarkGray'; continue }
            if ($t.member) {
                $tmp = Join-Path $env:TEMP ('logsim_' + [guid]::NewGuid().ToString('N') + '.zip')
                $exd = Join-Path $env:TEMP ('logsim_' + [guid]::NewGuid().ToString('N'))
                try {
                    Invoke-WebRequest -Uri $t.url -OutFile $tmp -UseBasicParsing -TimeoutSec 120
                    Expand-Archive -Path $tmp -DestinationPath $exd -Force
                    $src = Join-Path $exd ($t.member -replace '/', '\')
                    if (-not (Test-Path $src)) {
                        $leaf  = Split-Path $t.member -Leaf
                        $found = Get-ChildItem -Path $exd -Recurse -Filter $leaf -ErrorAction SilentlyContinue | Where-Object { $_.FullName -match '(?i)\\x64\\' } | Select-Object -First 1
                        if (-not $found) { $found = Get-ChildItem -Path $exd -Recurse -Filter $leaf -ErrorAction SilentlyContinue | Select-Object -First 1 }
                        if ($found) { $src = $found.FullName }
                    }
                    if (Test-Path $src) { Copy-Item -Path $src -Destination $dest -Force }
                } finally {
                    Remove-Item -Path $tmp -Force -ErrorAction SilentlyContinue
                    Remove-Item -Path $exd -Recurse -Force -ErrorAction SilentlyContinue
                }
            } else {
                Invoke-WebRequest -Uri $t.url -OutFile $dest -UseBasicParsing -TimeoutSec 120
            }
            if (Test-Path $dest) { Say ("   {0} staged at {1}" -f $t.name, $dest) 'Green' }
            else { Say ("   {0} not staged (download/extract failed, or the agent quarantined it; non-fatal)." -f $t.name) 'Yellow' }
        } catch { Say ("   {0} staging failed (non-fatal): {1}" -f $t.name, $_.Exception.Message) 'Yellow' }
    }
}

function Test-DownloadConnectivity {
    # Warn-only: stages that fetch at run time and cannot be pre-staged (the WildFire
    # test PE needs a fresh hash every run). Does not gate readiness.
    foreach ($h in @(
            @{ host='wildfire.paloaltonetworks.com'; port=80;  why='WildFire stage test PE (fresh each run, plain HTTP)' },
            @{ host='live.sysinternals.com';         port=443; why='ProcDump download fallback (HTTPS)' })) {
        $ok = $false
        try { $ok = (Test-NetConnection -ComputerName $h.host -Port $h.port -WarningAction SilentlyContinue -InformationLevel Quiet) } catch {}
        if ($ok) { Say ("   {0}:{1}: reachable" -f $h.host, $h.port) 'Green' }
        else { Say ("   {0}:{1}: NOT reachable -- {2} will fail until outbound is allowed." -f $h.host, $h.port, $h.why) 'Yellow' }
    }
}

function Get-Checks {
    $winrmOk  = ((Get-Service WinRM -ErrorAction SilentlyContinue).Status -eq 'Running')
    $atomicOk = (Test-Path $AtomicPsd1)
    $agentOk  = ((sc.exe query cyserver 2>$null) -match 'RUNNING')
    return [ordered]@{ winrm = [bool]$winrmOk; atomic = [bool]$atomicOk; cortex_agent = [bool]$agentOk }
}

function Get-Inventory($tests, $builtins, $source) {
    # Folded-in reporting: exactly what this box has, so the console shows it.
    $techs = @($tests | ForEach-Object { $_.id })
    $tools = [ordered]@{}
    foreach ($b in $builtins) {
        if ($b -eq 'procdump_lsass') { $tools[$b] = [bool](Test-Path (Join-Path $ToolsDir 'procdump64.exe')) }
        else { $tools[$b] = $true }   # built-in Windows binaries (regsvr32/scrobj, vssadmin)
    }
    foreach ($t in $ExtraTools) { if ($t.file) { $tools[$t.name] = [bool](Test-Path (Join-Path $ToolsDir $t.file)) } }
    $tokenOk = $false
    try { $tokenOk = ((Get-ItemProperty -Path $RegKeyPath -Name 'LocalAccountTokenFilterPolicy' -ErrorAction SilentlyContinue).LocalAccountTokenFilterPolicy -eq 1) } catch {}
    return [ordered]@{
        atomic_installed = [bool](Test-Path $AtomicPsd1)
        techniques       = @($techs)
        tools_staged     = $tools
        manifest_source  = $source
        token_policy     = [bool]$tokenOk
        self_heal_task   = [bool](Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue)
    }
}

function Send-Readiness($checks, $inventory, $mode, $allOk) {
    if ($NoPhoneHome -or -not $ConsoleUrl) { Say '   phone-home skipped.' 'DarkGray'; return }
    $ip = (Get-NetIPAddress -AddressFamily IPv4 |
           Where-Object { $_.IPAddress -notlike '169.254.*' -and $_.IPAddress -ne '127.0.0.1' -and $_.PrefixOrigin -ne 'WellKnown' } |
           Select-Object -First 1 -ExpandProperty IPAddress)
    $body = @{ hostname = $env:COMPUTERNAME; ip = $ip; ready = $allOk; mode = $mode;
               checks = $checks; inventory = $inventory; reported_at = (Get-Date).ToString('s') } | ConvertTo-Json -Compress -Depth 6
    try {
        Invoke-RestMethod -Method Post -Uri ("{0}/api/v1/attack/register" -f $ConsoleUrl.TrimEnd('/')) `
            -Headers @{ 'X-API-Key' = $Token } -ContentType 'application/json' -Body $body -TimeoutSec 15 | Out-Null
        Say '   readiness + inventory reported.' 'Green'
    } catch { Say ("   phone-home failed (non-fatal): {0}" -f $_.Exception.Message) 'DarkGray' }
}

function Register-RefreshTask {
    # The "run once" engine: a boot + daily task that re-runs this script in -Refresh
    # mode as SYSTEM, from a stable copy under $ToolsDir (so deleting the downloaded
    # .ps1 does not break it).
    try {
        New-Item -ItemType Directory -Force -Path $ToolsDir | Out-Null
        if ($PSCommandPath -and (Test-Path $PSCommandPath)) { Copy-Item -Path $PSCommandPath -Destination $SelfCopy -Force -ErrorAction SilentlyContinue }
        if (-not (Test-Path $SelfCopy)) { Say '   could not stage a script copy; self-heal task not created.' 'Yellow'; return }
        $act  = New-ScheduledTaskAction -Execute 'powershell.exe' `
                -Argument ('-NonInteractive -NoProfile -ExecutionPolicy Bypass -File "{0}" -Refresh' -f $SelfCopy)
        $trg  = @((New-ScheduledTaskTrigger -AtStartup), (New-ScheduledTaskTrigger -Daily -At (Get-Date -Hour 3 -Minute 0 -Second 0)))
        $prin = New-ScheduledTaskPrincipal -UserId 'SYSTEM' -LogonType ServiceAccount -RunLevel Highest
        $set  = New-ScheduledTaskSettingsSet -StartWhenAvailable -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries
        Register-ScheduledTask -TaskName $TaskName -Action $act -Trigger $trg -Principal $prin -Settings $set -Force `
            -Description 'LogSim XDR self-heal: re-assert attack config and provision new stages from the console manifest.' | Out-Null
        Say ("   self-heal task '{0}' registered (boot + daily 03:00)." -f $TaskName) 'Green'
    } catch { Say ("   self-heal task registration failed (non-fatal): {0}" -f $_.Exception.Message) 'Yellow' }
}

# ── Uninstall / rollback ──────────────────────────────────────────────────────
if ($Uninstall) {
    Say '== LogSim Kickstarter -- UNINSTALL ==' 'Cyan'
    try { Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false -ErrorAction SilentlyContinue } catch {}
    try { Disable-PSRemoting -Force -ErrorAction SilentlyContinue } catch {}
    Get-NetFirewallRule -DisplayName $FwRuleName -ErrorAction SilentlyContinue | Remove-NetFirewallRule -ErrorAction SilentlyContinue
    try { Remove-ItemProperty -Path $RegKeyPath -Name 'LocalAccountTokenFilterPolicy' -ErrorAction SilentlyContinue } catch {}
    if (Test-Path 'C:\AtomicRedTeam') { try { Remove-Item 'C:\AtomicRedTeam' -Recurse -Force -ErrorAction SilentlyContinue } catch {} }
    if (Test-Path $ToolsDir)          { try { Remove-Item $ToolsDir -Recurse -Force -ErrorAction SilentlyContinue } catch {} }
    Say 'Rollback complete (self-heal task + WinRM + firewall rule + token policy + atomics + staged tools removed).' 'Green'
    exit 0
}

# ── Refresh mode (the self-heal task runs this) ───────────────────────────────
if ($Refresh) {
    Say '== LogSim XDR Kickstarter -- REFRESH ==' 'Cyan'
    Assert-Config
    Ensure-Atomic                       # install only if missing, else import
    $m = Get-Manifest
    Install-Prereqs $m.tests            # fills gaps (new tests in the manifest)
    Stage-Tools $m.builtins             # stages gaps (new builtin-payload tools)
    Stage-ExtraTools $m.extra           # stages gaps (lab tools, e.g. Process Hacker)
    $checks = Get-Checks
    $allOk  = $checks.winrm -and $checks.atomic -and $checks.cortex_agent
    $inv    = Get-Inventory $m.tests $m.builtins $m.source
    Send-Readiness $checks $inv 'refresh' $allOk
    Say ("Refresh done (manifest: {0}; overall {1})." -f $m.source, ($(if($allOk){'GREEN'}else{'RED'}))) 'Cyan'
    exit 0
}

# ── First run (full provision) ────────────────────────────────────────────────
Say '== LogSim XDR Kickstarter ==' 'Cyan'
Say ("Console {0}, WinRM scoped to {1}" -f $ConsoleUrl, $ConsoleIP) 'DarkGray'

Say '[1/6] Enabling WinRM (scoped to the console)...' 'Yellow'
Assert-Config

Say '[2/6] Installing Atomic Red Team (unattended)...' 'Yellow'
Ensure-Atomic -FullInstall
$m = Get-Manifest
Say ("   provisioning from the {0} manifest ({1} test(s), {2} builtin tool(s))." -f $m.source, @($m.tests).Count, @($m.builtins).Count) 'DarkGray'
Install-Prereqs $m.tests

Say '[3/6] Staging tooling (builtin-payload + lab tools)...' 'Yellow'
if (@($m.builtins).Count -gt 0) { Stage-Tools $m.builtins } else { Say '   no builtin-payload tooling to stage.' 'DarkGray' }
if (@($m.extra).Count -gt 0) { Stage-ExtraTools $m.extra } else { Say '   no extra lab tools to stage.' 'DarkGray' }

Say '[4/6] Verifying Cortex agent + self-check...' 'Yellow'
$checks = Get-Checks
$allOk  = $checks.winrm -and $checks.atomic -and $checks.cortex_agent
foreach ($k in $checks.Keys) { Say ("   {0}: {1}" -f $k, ($(if($checks[$k]){'PASS'}else{'FAIL'}))) ($(if($checks[$k]){'Green'}else{'Red'})) }
if (-not $checks.cortex_agent) { Say '   (cyserver not running/installed -- no endpoint telemetry will be collected.)' 'Red' }
Say ("   OVERALL: {0}" -f ($(if($allOk){'GREEN - ready to fire'}else{'RED'}))) ($(if($allOk){'Green'}else{'Red'}))
Say '   outbound connectivity for run-time download stages (warn-only):' 'DarkGray'
Test-DownloadConnectivity

Say '[5/6] Registering the self-heal task (keeps this one run current)...' 'Yellow'
Register-RefreshTask

Say '[6/6] Reporting readiness + inventory to the console...' 'Yellow'
$inv = Get-Inventory $m.tests $m.builtins $m.source
Send-Readiness $checks $inv 'install' $allOk

Say ("`nDone. {0}" -f ($(if($allOk){'Box is preflight-green and self-healing (boot + daily).'}else{'Resolve the FAIL(s) above; the self-heal task will retry on schedule.'}))) 'Cyan'
'''


def render_kickstarter(*, console_url: str, console_ip: str, token: str = "",
                       technique_ids: Optional[List[str]] = None,
                       atomic_tests: Optional[List[dict]] = None,
                       builtin_payloads: Optional[List[str]] = None,
                       extra_tools: Optional[List[dict]] = None) -> str:
    """Render the one-shot .ps1 with the console's own values baked in.

    console_url : the base URL the box phones home to (e.g. http://192.168.0.45:5000)
    console_ip  : the WinRM client IP the box scopes its firewall rule to
    token       : scoped API token for the readiness phone-home (may be empty if
                  the console has no LOGSIM_API_KEY set)
    atomic_tests: [{"id","test_numbers"}, ...] — the box resolves prereqs for exactly
                  these pinned tests (`-GetPrereqs -TestNumbers`), never per-technique,
                  so unrelated tests' prereqs (e.g. the retired AzureAD module) are
                  never touched. Defaults to every registered story's pinned tests.
    technique_ids: legacy — a bare id list, mapped to test "1" each when atomic_tests
                  is not given.
    builtin_payloads: the builtin-payload names the stories use (payloads.py) → the
                  box stages their tooling (e.g. ProcDump) so the stages work without
                  a runtime download. Defaults to every registered builtin payload.
    """
    if atomic_tests is None:
        if technique_ids is not None:
            atomic_tests = [{"id": t, "test_numbers": "1"} for t in technique_ids]
        else:
            try:
                from .stories import all_atomic_tests
                atomic_tests = all_atomic_tests()
            except Exception:
                atomic_tests = [{"id": t, "test_numbers": "1"} for t in DEFAULT_TECHNIQUES]

    def _q(v):
        return "'" + str(v).replace("'", "''") + "'"
    tests_ps = ", ".join("@{{id={0};tests={1}}}".format(_q(t.get("id")), _q(t.get("test_numbers") or "1"))
                         for t in atomic_tests if t.get("id"))

    if builtin_payloads is None:
        try:
            from .stories import all_builtin_payloads
            builtin_payloads = all_builtin_payloads()
        except Exception:
            builtin_payloads = []
    builtins_ps = ", ".join(_q(p) for p in builtin_payloads)

    if extra_tools is None:
        extra_tools = EXTRA_TOOLS
    extra_ps = ", ".join(
        "@{{name={0};file={1};url={2};member={3}}}".format(
            _q(t.get("name")), _q(t.get("file")), _q(t.get("url")), _q(t.get("member") or ""))
        for t in extra_tools if t.get("file"))

    out = _TEMPLATE
    out = out.replace("__GENERATED_AT__", time.strftime("%Y-%m-%dT%H:%M:%S%z") or time.strftime("%Y-%m-%dT%H:%M:%S"))
    out = out.replace("__CONSOLE_URL__", console_url or "")
    out = out.replace("__CONSOLE_IP__", console_ip or "")
    out = out.replace("__TOKEN__", (token or "").replace("'", "''"))
    out = out.replace("__ATOMIC_TESTS__", tests_ps)
    out = out.replace("__BUILTINS__", builtins_ps)
    out = out.replace("__EXTRA_TOOLS__", extra_ps)
    return out
